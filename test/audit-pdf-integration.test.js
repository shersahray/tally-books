'use strict';
const {test:baseTest}=require('node:test');
const test=process.env.AUDIT_AI_PDF_INTEGRATION==='1'?baseTest:baseTest.skip;
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const {runWorker}=require('../src/server/audit-isolated');
const {extractPdf}=require('../src/server/audit-pdf');
// Generate synthetic PDFs with installed ImageMagick-free tools.
// ps2pdf and pdftoppm come from the CI test packages.
function pdf(text){
 const safe=text.replace(/[\\()]/g,'\\$&');
 const stream='BT /F1 16 Tf 50 700 Td ('+safe+') Tj ET';
 const objects=[
 '<< /Type /Catalog /Pages 2 0 R >>',
 '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
 '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
 '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
 '<< /Length '+Buffer.byteLength(stream)+' >>\nstream\n'+stream+'\nendstream'
 ];
 let out='%PDF-1.4\n',positions=[0];
 for(let i=0;i<objects.length;i++){positions.push(Buffer.byteLength(out));out+=(i+1)+' 0 obj\n'+objects[i]+'\nendobj\n';}
 const start=Buffer.byteLength(out);out+='xref\n0 6\n0000000000 65535 f \n';
 for(let i=1;i<positions.length;i++)out+=String(positions[i]).padStart(10,'0')+' 00000 n \n';
 out+='trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n'+start+'\n%%EOF\n';
 return Buffer.from(out);
}
const invoice='INVOICE INV-001 Supplier Example Total CAD 113.00 Date 2026-10-29';
test('real poppler extracts synthetic searchable invoice',async()=>{
 const r=await extractPdf(pdf(invoice),{ocr:false});
 assert.equal(r.pages,1);assert.equal(r.method,'pdf-text');assert.match(r.text,/INV-001/);
});
test('isolated CLI roundtrip uses genuine PDF extraction',async()=>{
 const file=require('node:path').resolve(__dirname,'../src/server/audit-worker-cli.js');
 const r=await runWorker(pdf(invoice),{command:process.execPath,args:[file]});
 assert.equal(r.pages,1);assert.match(r.text,/113.00/);
});
test('real OCR handles raster-only PDF generated by poppler',async()=>{
 const src=pdf('SCAN INVOICE 247 TOTAL 129.50');
 const {mkdtempSync,writeFileSync,readFileSync,rmSync}=require('node:fs');
 const {tmpdir}=require('node:os');const path=require('node:path');
 const dir=mkdtempSync(path.join(tmpdir(),'audit-ocr-test-'));
 try{
  const input=path.join(dir,'source.pdf'),prefix=path.join(dir,'page');
  writeFileSync(input,src);
  execFileSync('pdftoppm',['-f','1','-l','1','-r','150','-singlefile','-png',input,prefix]);
  const raster=path.join(dir,'scan.pdf');
  execFileSync('img2pdf',[prefix+'.png','-o',raster]);
  const output=await extractPdf(readFileSync(raster),{ocr:true});
  assert.equal(output.method,'ocr');assert.match(output.text,/INVOICE/i);
 }finally{rmSync(dir,{recursive:true,force:true});}
});
test('reject invalid PDF before spawning worker',()=>{
 assert.throws(()=>runWorker(Buffer.from('plain text'),{command:process.execPath}),/PDF/);
});
